package com.GLA.Methods;

public class Circle {
    public void circleOfArea(int radius) {
        double area = Math.PI * radius * radius;
        System.out.println("Area of Circle " + area);
    }

    public void Circum(int radius) {
        double per = 2 * Math.PI * radius * radius;
        System.out.println("Area of CircumFerence :- "+per);

    }

}
